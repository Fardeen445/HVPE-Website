CREATE DATABASE IF NOT EXISTS hvpe CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE hvpe;
DROP TABLE IF EXISTS order_items; DROP TABLE IF EXISTS orders; DROP TABLE IF EXISTS stock; DROP TABLE IF EXISTS products;
CREATE TABLE products (id INT PRIMARY KEY, name VARCHAR(100) NOT NULL, gender ENUM('men','women') NOT NULL,
  price DECIMAL(10,2) NOT NULL, sale_price DECIMAL(10,2) NULL, is_new TINYINT(1) NOT NULL DEFAULT 0);
CREATE TABLE stock (id INT AUTO_INCREMENT PRIMARY KEY, product_id INT NOT NULL, color VARCHAR(40) NOT NULL, size VARCHAR(5) NOT NULL,
  qty INT NOT NULL DEFAULT 0, UNIQUE KEY uq_variant (product_id,color,size), FOREIGN KEY (product_id) REFERENCES products(id));

